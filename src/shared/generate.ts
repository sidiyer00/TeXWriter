// Generated tables and figures: turn an output file (written by a script paired with the
// block, or by any other program) into the LaTeX in generated/<id>.tex.
//
//   table  ← .csv / .tsv / .txt (converted with every table style and multi-level headers)
//            or .tex (embedded as written; wrapped in a table float if it is a bare tabular)
//   figure ← .pdf / .png / .jpg / .eps  (\includegraphics)
import type { GeneratedBlockConfig } from './types';
import { escapeText } from './latex/inline';
import { hash } from './latex/scan';
import { flatRows, gridToTableBlock, guessHeaderRows, spanRows, tableNodeToExportGrid, textRows, type GridCell } from './latex/grid';
import { serializeTableBlock, TABLE_STYLES, type TableStyle } from './latex/table';
import { decodeFormat } from './latex/numfmt';

export interface TableView {
  kind: 'table';
  caption: string;
  label: string;
  columns: string[];
  rows: { cells: string[]; highlight: boolean; total?: boolean }[];
  sourceLine: string;
  style: string;
  /** header rows with merged cells; `columns` is then the last row */
  headers?: GridCell[][];
  /** the output was LaTeX: shown as source, not as a grid */
  latex?: string;
}
export interface FigureView { kind: 'figure'; caption: string; label: string; path: string; width: string }
export type BlockView = TableView | FigureView;

export interface RenderedBlock { tex: string; view: BlockView; hash: string }

export const TABLE_OUTPUTS = ['csv', 'tsv', 'txt', 'tex'];
export const FIGURE_OUTPUTS = ['pdf', 'png', 'jpg', 'jpeg', 'eps'];

const ext = (p: string) => (/\.([A-Za-z0-9]+)$/.exec(p)?.[1] ?? '').toLowerCase();
const header = (cfg: GeneratedBlockConfig) =>
  `% Generated by TeXWriter from ${cfg.output}${cfg.script ? ` (written by ${cfg.script})` : ''}. Edit the script, the output or the block's properties; this file is rewritten.`;

/** Default output path for a new block. */
export function defaultOutput(id: string, kind: 'table' | 'figure'): string {
  return `outputs/${id}.${kind === 'table' ? 'csv' : 'pdf'}`;
}

/**
 * The command that runs a script, from its extension. {python} is the project's Python,
 * {script} and {output} are project-relative paths (the working directory is the project).
 */
export function defaultCommand(script: string): string {
  switch (ext(script)) {
    case 'py': return '{python} "{script}"';
    case 'r': return 'Rscript "{script}"';
    case 'jl': return 'julia "{script}"';
    case 'js': case 'mjs': return 'node "{script}"';
    case 'sh': return 'bash "{script}"';
    case 'ps1': return 'powershell -NoProfile -ExecutionPolicy Bypass -File "{script}"';
    case 'm': return 'matlab -batch "run(\'{script}\')"';
    default: return '"{script}"';
  }
}

/** A table built from CSV/TSV text: same converter as pasted spreadsheet data. */
export function renderDataTable(cfg: GeneratedBlockConfig, text: string): RenderedBlock {
  const file = cfg.output ?? '';
  const all = textRows(text, ext(file) === 'tsv' ? '\t' : undefined);
  if (!all.length) throw new Error(`${file} has no rows`);
  const h = Math.max(0, Math.min(cfg.headerRows ?? guessHeaderRows(all), all.length - 1, 6));
  // column choice and renaming work on the last header row's labels
  const names = h ? all[h - 1] : all[0].map((_, i) => `Column ${i + 1}`);
  const order = (cfg.columns?.length ? cfg.columns.map((c) => names.indexOf(c)).filter((i) => i >= 0) : names.map((_, i) => i))
    .filter((i) => !(cfg.hiddenColumns ?? []).includes(names[i]));
  const idx = order.length ? order : names.map((_, i) => i);
  const rows = all.map((r, ri) => idx.map((i) => (ri === h - 1 && cfg.columnLabels?.[names[i]] != null ? cfg.columnLabels[names[i]] : r[i] ?? '')));
  const grid = spanRows(rows, h);
  const style = (TABLE_STYLES.some((t) => t.id === cfg.tableStyle) ? cfg.tableStyle : 'booktabs') as TableStyle;
  const node = gridToTableBlock(grid, { style, caption: cfg.caption ?? '', label: cfg.label ?? '', size: cfg.size ?? '', format: decodeFormat(cfg.numberFormat) });
  let body = serializeTableBlock(node);
  if (cfg.fitWidth) body = body.replace(/^( *)\\begin\{tabular\}/m, '$1\\resizebox{\\linewidth}{!}{%\n$1\\begin{tabular}').replace(/\\end\{tabular\}/, '\\end{tabular}%\n  }');
  if (cfg.sourceLine) body = body.replace(/\n\\end\{table\}$/, `\n  \\par\\smallskip{\\footnotesize Source: \\texttt{${escapeText(file)}}.}\n\\end{table}`);
  const tex = `${header(cfg)}\n${body}\n`;
  const flat = flatRows(tableNodeToExportGrid(node));
  return {
    tex,
    hash: hash(tex),
    view: {
      kind: 'table', caption: cfg.caption ?? '', label: cfg.label ?? '',
      columns: h ? flat[h - 1] : flat[0].map(() => ''), headers: grid.rows.slice(0, h),
      rows: flat.slice(h).map((cells) => ({ cells, highlight: false })), sourceLine: file, style,
    },
  };
}

/** A table the script wrote as LaTeX: a whole table float is used as is, a bare tabular is wrapped. */
export function renderTexTable(cfg: GeneratedBlockConfig, text: string): RenderedBlock {
  const src = text.replace(/\s+$/, '');
  let body: string;
  if (/\\begin\{table\*?\}/.test(src)) body = src;
  else {
    const L = ['\\begin{table}[htbp]', '  \\centering'];
    if (cfg.size) L.push(`  \\${cfg.size}`);
    if (cfg.caption) L.push(`  \\caption{${cfg.caption}}`);
    if (cfg.label) L.push(`  \\label{${cfg.label}}`);
    L.push(cfg.fitWidth ? `  \\resizebox{\\linewidth}{!}{%\n${src}%\n  }` : src);
    if (cfg.sourceLine) L.push(`  \\par\\smallskip{\\footnotesize Source: \\texttt{${escapeText(cfg.output ?? '')}}.}`);
    L.push('\\end{table}');
    body = L.join('\n');
  }
  const tex = `${header(cfg)}\n${body}\n`;
  return { tex, hash: hash(tex), view: { kind: 'table', caption: cfg.caption ?? '', label: cfg.label ?? '', columns: [], rows: [], sourceLine: cfg.output ?? '', style: cfg.tableStyle ?? 'booktabs', latex: src } };
}

export function renderFigure(cfg: GeneratedBlockConfig): RenderedBlock {
  const width = cfg.width || '0.8\\linewidth';
  const L = [header(cfg), '\\begin{figure}[htbp]', '  \\centering', `  \\includegraphics[width=${width}]{${cfg.output}}`];
  if (cfg.caption) L.push(`  \\caption{${cfg.caption}}`);
  if (cfg.label) L.push(`  \\label{${cfg.label}}`);
  if (cfg.sourceLine) L.push(`  \\par\\smallskip{\\footnotesize Source: \\texttt{${escapeText(cfg.output ?? '')}}.}`);
  L.push('\\end{figure}');
  const tex = L.join('\n') + '\n';
  return { tex, hash: hash(tex), view: { kind: 'figure', caption: cfg.caption ?? '', label: cfg.label ?? '', path: cfg.output ?? '', width } };
}

/** Render a block from its output. `text` is the output's content for tables (null for figures). */
export function renderGenerated(cfg: GeneratedBlockConfig, text: string | null): RenderedBlock {
  if (!cfg.output) throw new Error('No output file is set for this block.');
  const e = ext(cfg.output);
  if (cfg.kind === 'figure') {
    if (!FIGURE_OUTPUTS.includes(e)) throw new Error(`${cfg.output}: figures must be ${FIGURE_OUTPUTS.join(', ')} files`);
    return renderFigure(cfg);
  }
  if (cfg.kind !== 'table') throw new Error('Generated text summaries from earlier versions are no longer supported. Convert this block to static LaTeX.');
  if (text === null) throw new Error(`${cfg.output} could not be read`);
  if (e === 'tex') return renderTexTable(cfg, text);
  return renderDataTable(cfg, text);
}

/** LaTeX for a block whose output does not exist yet: a labelled placeholder, so references resolve. */
export function pendingTex(cfg: GeneratedBlockConfig): string {
  const env = cfg.kind === 'figure' ? 'figure' : 'table';
  const what = cfg.script ? `Run ${cfg.script} to generate this ${env}` : `Waiting for ${cfg.output ?? 'an output file'}`;
  return [
    `% Generated by TeXWriter. Not generated yet: ${what.toLowerCase()}.`,
    `\\begin{${env}}[htbp]`,
    '  \\centering',
    cfg.caption ? `  \\caption{${cfg.caption}}` : '',
    cfg.label ? `  \\label{${cfg.label}}` : '',
    `  \\fbox{\\parbox{0.8\\linewidth}{\\centering\\small\\itshape ${escapeText(what)}.}}`,
    `\\end{${env}}`,
  ].filter(Boolean).join('\n') + '\n';
}

// ------------------------------------------------------------------ starter scripts

export type ScriptLanguage = 'python' | 'r';

const pyDoc = (kind: 'table' | 'figure', label: string) => `"""${kind === 'table' ? 'Table' : 'Figure'} ${label} for the document.

TeXWriter runs this script (Run on the ${kind}, or Run all) with the project folder as the
working directory, then ${kind === 'table' ? 'turns the CSV it writes into a LaTeX table' : 'includes the figure it saves'}.
Replace the example with your own code: load data, call your model, compute results.
"""`;

/** A runnable example script that writes `output`; the user replaces the example part. */
export function starterScript(kind: 'table' | 'figure', lang: ScriptLanguage, output: string, label: string): string {
  if (lang === 'r') {
    if (kind === 'table') {
      return `# Table ${label} for the document.
# TeXWriter runs this script with the project folder as the working directory and turns
# the CSV it writes into a LaTeX table. Replace the example with your own code.

output <- Sys.getenv("TEXWRITER_OUTPUT", "${output}")
dir.create(dirname(output), showWarnings = FALSE, recursive = TRUE)

# --- example: summary statistics by group -------------------------------------------
set.seed(1)
df <- data.frame(group = rep(c("A", "B", "C"), each = 50), value = rnorm(150, mean = rep(c(10, 12, 15), each = 50)))
result <- aggregate(value ~ group, data = df, FUN = function(v) c(n = length(v), mean = mean(v), sd = sd(v)))
result <- do.call(data.frame, result)
names(result) <- c("Group", "N", "Mean", "Std. dev.")
# -------------------------------------------------------------------------------------

write.csv(result, output, row.names = FALSE)
`;
    }
    return `# Figure ${label} for the document.
# TeXWriter runs this script with the project folder as the working directory and
# includes the figure it saves. Replace the example with your own plot.

output <- Sys.getenv("TEXWRITER_OUTPUT", "${output}")
dir.create(dirname(output), showWarnings = FALSE, recursive = TRUE)

pdf(output, width = 6, height = 4)
# --- example ---------------------------------------------------------------------------
x <- seq(0, 10, length.out = 200)
plot(x, sin(x) * exp(-x / 5), type = "l", lwd = 2, xlab = "x", ylab = "y")
grid()
# -------------------------------------------------------------------------------------
invisible(dev.off())
`;
  }
  if (kind === 'table') {
    return `${pyDoc('table', label)}
import csv
import os
import random
import statistics

# TeXWriter sets TEXWRITER_OUTPUT to the file it reads; running the script by hand
# writes to the same place.
OUTPUT = os.environ.get("TEXWRITER_OUTPUT", "${output}")
os.makedirs(os.path.dirname(OUTPUT) or ".", exist_ok=True)

# --- example: summary statistics by group ---------------------------------------------
random.seed(1)
data = {g: [random.gauss(mu, 2.0) for _ in range(50)] for g, mu in [("A", 10), ("B", 12), ("C", 15)]}
rows = [[g, len(v), round(statistics.mean(v), 3), round(statistics.stdev(v), 3)] for g, v in data.items()]
# ---------------------------------------------------------------------------------------

# One header row; write two (e.g. a group label row above the column names) for a
# multi-level header. With pandas: df.to_csv(OUTPUT, index=False)
with open(OUTPUT, "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["Group", "N", "Mean", "Std. dev."])
    w.writerows(rows)
`;
  }
  return `${pyDoc('figure', label)}
import math
import os
import sys

OUTPUT = os.environ.get("TEXWRITER_OUTPUT", "${output}")
os.makedirs(os.path.dirname(OUTPUT) or ".", exist_ok=True)

try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    sys.exit("This figure needs matplotlib: run  pip install matplotlib  (or set the Python "
             "interpreter in Document setup → Generated content).")

# --- example --------------------------------------------------------------------------
x = [i / 20 for i in range(201)]
y = [math.sin(v) * math.exp(-v / 5) for v in x]
fig, ax = plt.subplots(figsize=(6, 3.6))
ax.plot(x, y, linewidth=2)
ax.set_xlabel("x")
ax.set_ylabel("y")
ax.grid(alpha=0.3)
# ---------------------------------------------------------------------------------------

fig.savefig(OUTPUT, bbox_inches="tight")
`;
}
