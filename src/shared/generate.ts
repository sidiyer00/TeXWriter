// Render generated report content (tables, summaries, figures) from a test run.
import type { GeneratedBlockConfig, RunMeta, RunResults, TestResult } from './types';
import type { Table } from './csv';
import { escapeText } from './latex/inline';
import { hash } from './latex/scan';
import { flatRows, gridToTableBlock, guessHeaderRows, spanRows, tableNodeToExportGrid, textRows, type GridCell } from './latex/grid';
import { serializeTableBlock, TABLE_STYLES, type TableStyle } from './latex/table';
import { decodeFormat } from './latex/numfmt';

export interface TableView {
  kind: 'table';
  caption: string;
  label: string;
  columns: string[];
  rows: { cells: string[]; highlight: boolean; total?: boolean }[];
  sourceLine: string;
  style: string;
  /** header rows with merged cells (data-file tables); `columns` is then the last row */
  headers?: GridCell[][];
}
export interface SummaryView { kind: 'summary'; text: string; values: string[] }
export interface FigureView { kind: 'figure'; caption: string; label: string; path: string; width: string }
export type BlockView = TableView | SummaryView | FigureView;

export interface RenderedBlock { tex: string; view: BlockView; hash: string }

const isNum = (s: string) => s.trim() !== '' && /^[-+]?(\d+\.?\d*|\.\d+)(e[-+]?\d+)?$/i.test(s.trim());

export function formatNumber(raw: string, col: string, cfg: GeneratedBlockConfig): string {
  if (!isNum(raw)) return raw;
  const v = Number(raw);
  const dec = cfg.decimals ?? 2;
  const pct = cfg.percentColumns?.includes(col);
  if (pct) return `${(v * 100).toFixed(dec)}%`;
  if (Number.isInteger(v) && !/\./.test(raw)) return v.toLocaleString('en-US');
  // p-values: show 3 decimals when below 0.05
  if (/(^|\b)p(-|_|\s)?(value)?\b|jeffreys|p$/i.test(col) && Math.abs(v) < 0.05 && v !== 0) return v.toFixed(Math.max(dec, 3));
  return v.toFixed(dec);
}

/** Plain-text provenance line for a run (escape with escapeText before putting it in LaTeX). */
export function sourceLineFor(meta: RunMeta): string {
  const date = new Date(meta.startedAt).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
  const parts = [`${meta.suite}, run #${meta.number} (${date})`];
  if (meta.gitCommit) parts.push(`commit ${meta.gitCommit}`);
  if (meta.dataSnapshot) parts.push(`data snapshot ${meta.dataSnapshot}`);
  return parts.join(', ');
}

export function renderTable(cfg: GeneratedBlockConfig, table: Table, meta: RunMeta): RenderedBlock {
  const allCols = table.header;
  const cols = (cfg.columns?.length ? cfg.columns : allCols).filter((c) => allCols.includes(c) && !(cfg.hiddenColumns ?? []).includes(c));
  const idx = cols.map((c) => allCols.indexOf(c));
  const labels = cols.map((c) => cfg.columnLabels?.[c] ?? c);
  const numericCol = idx.map((k) => table.rows.every((r) => r[k] === undefined || r[k].trim() === '' || isNum(r[k]) || r[k].trim() === '—'));
  const hl = cfg.highlight;
  const hlIdx = hl ? allCols.indexOf(hl.column) : -1;
  const rows = table.rows.map((r) => {
    const total = /^(all|total|portfolio)$/i.test((r[0] ?? '').trim());
    return {
      cells: idx.map((k, j) => formatNumber(r[k] ?? '', cols[j], cfg)),
      highlight: hlIdx >= 0 && (r[hlIdx] ?? '').trim().toLowerCase() === hl!.equals.trim().toLowerCase(),
      total,
    };
  }).filter((r) => cfg.totalRow !== false || !r.total);
  const style = cfg.style ?? 'booktabs';
  const align = numericCol.map((n) => (n ? 'r' : 'l'));
  const colSpec = style === 'grid' ? `|${align.join('|')}|` : align.join('');
  const L: string[] = [];
  L.push(`% Generated by Quire from run #${meta.number} (${cfg.source ?? ''}). Do not edit; change it in Table properties.`);
  L.push('\\begin{table}[htbp]');
  L.push('  \\centering');
  if (cfg.caption) L.push(`  \\caption{${cfg.caption}}`);
  if (cfg.label) L.push(`  \\label{${cfg.label}}`);
  if (cfg.fitWidth) L.push('  \\resizebox{\\linewidth}{!}{%');
  L.push(`  \\begin{tabular}{${colSpec}}`);
  L.push(style === 'booktabs' ? '    \\toprule' : style === 'grid' ? '    \\hline' : '');
  L.push(`    ${labels.map((l) => `\\textbf{${escapeText(l)}}`).join(' & ')} \\\\`);
  L.push(style === 'booktabs' ? '    \\midrule' : style === 'grid' ? '    \\hline' : '    \\hline');
  for (const r of rows) {
    if (r.total) L.push(style === 'booktabs' ? '    \\midrule' : '    \\hline');
    const cells = r.cells.map((c) => escapeText(c));
    const line = r.highlight ? cells.map((c) => `\\textbf{${c}}`).join(' & ') : cells.join(' & ');
    L.push(`    ${r.highlight ? '\\rowcolor{quireshade} ' : ''}${line} \\\\${style === 'grid' ? ' \\hline' : ''}`);
  }
  if (style === 'booktabs') L.push('    \\bottomrule');
  else if (style === 'minimal') L.push('    \\hline');
  L.push('  \\end{tabular}');
  if (cfg.fitWidth) L.push('  }');
  const sl = sourceLineFor(meta);
  if (cfg.sourceLine !== false) L.push(`  \\par\\smallskip{\\footnotesize Source: ${escapeText(sl)}.}`);
  L.push('\\end{table}');
  const tex = L.filter((l) => l !== '').join('\n') + '\n';
  return {
    tex,
    hash: hash(tex),
    view: { kind: 'table', caption: cfg.caption ?? '', label: cfg.label ?? '', columns: labels, rows, sourceLine: sl, style },
  };
}

/**
 * A table linked to a CSV/TSV file in the project. The file is converted with the same
 * code as pasted spreadsheet data, so every table style and multi-level header works; the
 * result is written to generated/<id>.tex and pulled in with \\input.
 */
export function renderDataTable(cfg: GeneratedBlockConfig, text: string): RenderedBlock {
  const file = cfg.dataFile ?? '';
  const all = textRows(text, /\.tsv$/i.test(file) ? '\t' : undefined);
  if (!all.length) throw new Error(`${file} has no rows`);
  const h = Math.max(0, Math.min(cfg.headerRows ?? guessHeaderRows(all), all.length - 1, 6));
  // column choice and renaming work on the last header row's labels
  const names = h ? all[h - 1] : all[0].map((_, i) => `Column ${i + 1}`);
  const order = (cfg.columns?.length ? cfg.columns.map((c) => names.indexOf(c)).filter((i) => i >= 0) : names.map((_, i) => i))
    .filter((i) => !(cfg.hiddenColumns ?? []).includes(names[i]));
  const idx = order.length ? order : names.map((_, i) => i);
  const rows = all.map((r, ri) => idx.map((i) => (ri === h - 1 && cfg.columnLabels?.[names[i]] != null ? cfg.columnLabels[names[i]] : r[i] ?? '')));
  const grid = spanRows(rows, h);
  const style = (TABLE_STYLES.some((t) => t.id === cfg.tableStyle) ? cfg.tableStyle : 'booktabs') as TableStyle;
  const node = gridToTableBlock(grid, { style, caption: cfg.caption ?? '', label: cfg.label ?? '', size: cfg.size ?? '', format: decodeFormat(cfg.numberFormat) });
  let body = serializeTableBlock(node);
  if (cfg.fitWidth) body = body.replace(/^( *)\\begin\{tabular\}/m, '$1\\resizebox{\\linewidth}{!}{%\n$1\\begin{tabular}').replace(/\\end\{tabular\}/, '\\end{tabular}%\n  }');
  if (cfg.sourceLine) body = body.replace(/\n\\end\{table\}$/, `\n  \\par\\smallskip{\\footnotesize Source: \\texttt{${escapeText(file)}}.}\n\\end{table}`);
  const tex = `% Generated by Quire from ${file}. Edit the data file or the table's properties; this file is rewritten.\n${body}\n`;
  const flat = flatRows(tableNodeToExportGrid(node));
  return {
    tex,
    hash: hash(tex),
    view: {
      kind: 'table', caption: cfg.caption ?? '', label: cfg.label ?? '',
      columns: h ? flat[h - 1] : flat[0].map(() => ''), headers: grid.rows.slice(0, h),
      rows: flat.slice(h).map((cells) => ({ cells, highlight: false })), sourceLine: file, style,
    },
  };
}

/** Resolve {{test.id.field}} placeholders. field ∈ value|status|threshold|name|metric|details.KEY */
export function resolveTemplate(template: string, results: RunResults, cfg: GeneratedBlockConfig): { text: string; values: string[] } {
  const byId = new Map(results.tests.map((t) => [t.id, t] as const));
  const values: string[] = [];
  const text = template.replace(/\{\{\s*([^}]+?)\s*\}\}/g, (_m, path: string) => {
    const segs = path.split('.');
    // test ids contain dots: find the longest prefix that is a test id
    for (let k = segs.length - 1; k > 0; k--) {
      const id = segs.slice(0, k).join('.');
      const t = byId.get(id);
      if (!t) continue;
      const field = segs.slice(k);
      let v: unknown;
      if (field[0] === 'details') v = t.details?.[field.slice(1).join('.')];
      else v = (t as unknown as Record<string, unknown>)[field[0]];
      let s = v === undefined || v === null ? '??' : typeof v === 'number' ? formatNumber(String(v), field.join('.'), cfg) : String(v);
      if (field[0] === 'value' && typeof v === 'number' && t.metric && /p-?value/i.test(t.metric)) s = v < 0.05 ? v.toFixed(3) : v.toFixed(2);
      values.push(s);
      return s;
    }
    values.push('??');
    return '??';
  });
  return { text, values };
}

export function renderSummary(cfg: GeneratedBlockConfig, results: RunResults, meta: RunMeta): RenderedBlock {
  const template = cfg.template ?? '';
  const { values } = resolveTemplate(template, results, cfg);
  let k = 0;
  // the template is LaTeX prose written by the author: keep it, escape only resolved values
  const body = template.replace(/\{\{\s*([^}]+?)\s*\}\}/g, () => escapeText(values[k++] ?? '??'));
  const tex = `% Generated by Quire from run #${meta.number}. Edit the wording in the block's properties.\n${body}\n`;
  return { tex, hash: hash(tex), view: { kind: 'summary', text: body, values } };
}

export function renderFigure(cfg: GeneratedBlockConfig, assetPath: string, meta: RunMeta): RenderedBlock {
  const L = [
    `% Generated by Quire from run #${meta.number} (${cfg.source ?? ''}).`,
    '\\begin{figure}[htbp]',
    '  \\centering',
    `  \\includegraphics[width=${cfg.width || '0.85\\linewidth'}]{${assetPath}}`,
  ];
  if (cfg.caption) L.push(`  \\caption{${cfg.caption}}`);
  if (cfg.label) L.push(`  \\label{${cfg.label}}`);
  if (cfg.sourceLine !== false) L.push(`  \\par\\smallskip{\\footnotesize Source: ${escapeText(sourceLineFor(meta))}.}`);
  L.push('\\end{figure}');
  const tex = L.join('\n') + '\n';
  return { tex, hash: hash(tex), view: { kind: 'figure', caption: cfg.caption ?? '', label: cfg.label ?? '', path: assetPath, width: cfg.width || '0.85\\linewidth' } };
}

export function defaultSummaryTemplate(t: TestResult): string {
  const v = `{{${t.id}.value}}`;
  const verb = t.status === 'passed' ? 'passed' : t.status === 'failed' ? 'failed' : t.status === 'warning' ? 'raised a warning on' : 'was skipped for';
  const name = escapeText(t.name);
  if (t.status === 'skipped') return `${name} was not run: {{${t.id}.notes}}.`;
  return `${name} ${verb} its threshold (${t.metric ?? 'value'} = ${v}; threshold ${escapeText(t.threshold ?? 'n/a')}).`;
}

export function blockStatus(cfg: GeneratedBlockConfig, latestRun: number | null): 'fresh' | 'stale' {
  if (latestRun === null) return 'fresh';
  return cfg.followLatest && cfg.run < latestRun ? 'stale' : 'fresh';
}
